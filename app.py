"""Restaurant sales dashboard with filters and operational summaries.

Run locally with: streamlit run app.py
The data is fictional and generated by src/generate_data.py.
"""
from pathlib import Path
import subprocess
import sys

import pandas as pd
import plotly.express as px
import streamlit as st

ROOT = Path(__file__).resolve().parent
DATA_DIR = ROOT / "data"

st.set_page_config(page_title="Restaurant Sales | Analytics", page_icon="🍽️", layout="wide")

@st.cache_data
def load_data():
    files = {name: DATA_DIR / f"{name}.csv" for name in ["menu", "customers", "orders", "order_items"]}
    if not all(path.exists() for path in files.values()):
        subprocess.run([sys.executable, str(ROOT / "src" / "generate_data.py")], check=True)
    return {name: pd.read_csv(path, parse_dates=["order_datetime"] if name == "orders" else None) for name, path in files.items()}

tables = load_data()
orders, items, menu, customers = tables["orders"], tables["order_items"], tables["menu"], tables["customers"]
data = orders.merge(items, on="order_id", how="inner").merge(menu[["menu_item_id", "item_name", "category"]], on="menu_item_id").merge(customers, on="customer_id", how="left")
data = data[data["order_status"].eq("Completed")].copy()
data["revenue"] = data["quantity"] * data["unit_price"]
data["estimated_cost"] = data["quantity"] * data["estimated_unit_cost"]
data["estimated_contribution"] = data["revenue"] - data["estimated_cost"]
data["order_date"] = data["order_datetime"].dt.date
data["month"] = data["order_datetime"].dt.to_period("M").astype(str)

st.set_page_config(page_title="Restaurant Sales | Analytics", page_icon="🍽️", layout="wide")
st.title("Restaurant Sales & Menu Performance")
st.caption("Understand revenue mix, ordering patterns and estimated contribution · Fictional portfolio dataset")

with st.sidebar:
    st.header("Report filters")
    min_date, max_date = data["order_datetime"].min().date(), data["order_datetime"].max().date()
    date_range = st.date_input("Order date", value=(min_date, max_date), min_value=min_date, max_value=max_date)
    channels = sorted(data["order_channel"].unique())
    selected_channels = st.multiselect("Order channel", channels, default=channels)
    categories = sorted(data["category"].unique())
    selected_categories = st.multiselect("Menu category", categories, default=categories)
    segments = sorted(data["customer_segment"].dropna().unique())
    selected_segments = st.multiselect("Customer segment", segments, default=segments)

filtered = data.copy()
if isinstance(date_range, (tuple, list)) and len(date_range) == 2:
    start_date, end_date = pd.Timestamp(date_range[0]), pd.Timestamp(date_range[1]) + pd.Timedelta(days=1)
    filtered = filtered[filtered["order_datetime"].between(start_date, end_date, inclusive="left")]
filtered = filtered[
    filtered["order_channel"].isin(selected_channels)
    & filtered["category"].isin(selected_categories)
    & filtered["customer_segment"].isin(selected_segments)
]

if filtered.empty:
    st.warning("No completed order lines match these filters. Widen the date range or choose more categories.")
    st.stop()

order_level = filtered.groupby("order_id", as_index=False).agg(order_revenue=("revenue", "sum"), order_contribution=("estimated_contribution", "sum"))
revenue = filtered["revenue"].sum()
contribution = filtered["estimated_contribution"].sum()
orders_count = order_level["order_id"].nunique()
average_order_value = order_level["order_revenue"].mean()
unique_customers = filtered["customer_id"].nunique()

kpis = st.columns(5)
kpis[0].metric("Revenue", f"₹{revenue:,.0f}")
kpis[1].metric("Completed orders", f"{orders_count:,}")
kpis[2].metric("Average order value", f"₹{average_order_value:,.0f}")
kpis[3].metric("Unique customers", f"{unique_customers:,}")
kpis[4].metric("Estimated contribution", f"₹{contribution:,.0f}")

left, right = st.columns(2)
with left:
    daily = filtered.groupby("order_date", as_index=False).agg(revenue=("revenue", "sum"))
    fig = px.line(daily, x="order_date", y="revenue", title="Daily revenue trend", markers=True, labels={"order_date": "Order date", "revenue": "Revenue (₹)"})
    st.plotly_chart(fig, use_container_width=True)
with right:
    category_summary = filtered.groupby("category", as_index=False).agg(revenue=("revenue", "sum")).sort_values("revenue", ascending=False)
    fig = px.bar(category_summary, x="category", y="revenue", color="revenue", color_continuous_scale="Teal", title="Revenue by menu category", labels={"category": "Category", "revenue": "Revenue (₹)"})
    st.plotly_chart(fig, use_container_width=True)

left, right = st.columns(2)
with left:
    channel_summary = filtered.groupby("order_channel", as_index=False).agg(revenue=("revenue", "sum"))
    fig = px.pie(channel_summary, names="order_channel", values="revenue", hole=0.55, title="Revenue by order channel")
    st.plotly_chart(fig, use_container_width=True)
with right:
    item_summary = filtered.groupby("item_name", as_index=False).agg(quantity_sold=("quantity", "sum"), revenue=("revenue", "sum"), estimated_contribution=("estimated_contribution", "sum")).sort_values("revenue", ascending=True).tail(10)
    fig = px.bar(item_summary, x="revenue", y="item_name", orientation="h", color="estimated_contribution", color_continuous_scale="Blues", title="Top menu items by revenue", labels={"revenue": "Revenue (₹)", "item_name": "", "estimated_contribution": "Est. contribution (₹)"})
    st.plotly_chart(fig, use_container_width=True)

st.subheader("Menu item performance")
st.dataframe(item_summary.sort_values("revenue", ascending=False), use_container_width=True, hide_index=True)
st.download_button("Download filtered sales detail", filtered.to_csv(index=False).encode("utf-8"), "restaurant_sales_filtered.csv", "text/csv")

with st.expander("Metric notes"):
    st.write("Revenue is quantity multiplied by menu price for completed order lines. Estimated contribution subtracts the dataset's estimated unit cost; it is not audited gross profit and excludes labour, rent, tax, delivery commissions and other overheads. All records are fictional.")
